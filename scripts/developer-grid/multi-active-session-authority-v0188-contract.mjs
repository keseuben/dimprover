#!/usr/bin/env node
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"../..");
const read=p=>fs.readFileSync(path.join(root,p),"utf8");
const work=read("app/lib/developer-grid/work-start.ts");
const exec=read("app/lib/developer-grid/execution-bridge.ts");
const hb=read("app/lib/developer-grid/session-heartbeat.ts");
const ev=read("app/lib/developer-grid/evidence-ingest.ts");
const review=read("app/lib/developer-grid/review-gate.ts");
const build=read("app/lib/developer-grid/build-runs.ts");
const close=read("app/lib/developer-grid/work-close.ts");
const vg=read("app/lib/developer-grid/vguard-review.ts");
const pkg=JSON.parse(read("desktop/benjadmin-developer-grid/package.json"));
let n=0; const check=(name,fn)=>{fn();n++;console.log("PASS",name);};
check("desktop v0.1.88",()=>assert.equal(pkg.version,"0.1.88"));
check("task resolver exists",()=>assert.match(work,/export async function getDeveloperGridTaskById/));
check("BOOT ACK resolves task by id",()=>assert.match(work,/const authoritativeTask = await getDeveloperGridTaskById\(taskId\)/));
check("BOOT ACK does not require global pointer",()=>assert.doesNotMatch(work.slice(work.indexOf("export async function recordDeveloperGridBootAck"),work.indexOf("function normalizeSurfaceType")),/!state\.task \|\| state\.task\.id !== taskId/));
check("execution bridge uses exact session task",()=>assert.match(exec,/session\.id === sessionId && session\.taskId === taskId && session\.endedAt === null/));
check("execution bridge no global active-work gate",()=>assert.doesNotMatch(exec,/getDeveloperGridActiveWork/));
check("heartbeat resolves task by id",()=>assert.match(hb,/getDeveloperGridTaskById\(taskId\)/));
check("evidence resolves task by id",()=>assert.match(ev,/getDeveloperGridTaskById\(taskId\)/));
check("review gate resolves task by id",()=>assert.match(review,/getDeveloperGridTaskById\(taskId\)/));
check("build gate resolves task by id",()=>assert.match(build,/getDeveloperGridTaskById\(taskId\)/));
check("close gate resolves task by id",()=>assert.match(close,/getDeveloperGridTaskById\(taskId\)/));
check("VGuard resolves task by id",()=>assert.match(vg,/getDeveloperGridTaskById\(resolvedTaskId\)/));
console.log("Developer Grid v0.1.88 multi-active session authority contract PASS · "+n+"/"+n);
