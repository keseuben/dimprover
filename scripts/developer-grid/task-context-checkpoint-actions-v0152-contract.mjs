#!/usr/bin/env node
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(here,"..","..");
const read=(relative)=>fs.readFileSync(path.join(root,relative),"utf8");

const renderer=read("desktop/benjadmin-developer-grid/src/renderer/renderer.js");
const main=read("desktop/benjadmin-developer-grid/src/main.cjs");
const html=read("desktop/benjadmin-developer-grid/src/renderer/index.html");
const live=read("desktop/benjadmin-developer-grid/src/live/benjadmin-live-client.cjs");
const prompt=read("desktop/benjadmin-developer-grid/src/stage-actions-prompt-builder.cjs");

let n=0;
const check=(label,fn)=>{fn();n++;console.log("PASS "+String(n).padStart(2,"0")+" "+label);};

check("Task Inspector overlay exists",()=>assert.match(html,/id="taskInspectorLayer"[\s\S]*data-testid="developer-grid-task-inspector"/));
check("current-task opens Task Inspector",()=>assert.match(renderer,/action === "current-task"[\s\S]{0,180}openTaskInspector\(workerCode, "task"\)/));
check("current-task is not toast-only",()=>assert.doesNotMatch(renderer,/action === "current-task"[\s\S]{0,240}showToast\("Aktuális task"/));
check("context opens task-specific inspector",()=>assert.match(renderer,/action === "context"[\s\S]{0,180}openTaskInspector\(workerCode, "context"\)/));
check("cell context no longer opens global Context Workspace",()=>assert.doesNotMatch(renderer,/action === "context"[\s\S]{0,240}contextWorkspaceMode\("open"\)/));
check("checkpoint exact guard exists",()=>{assert.match(main,/function checkpointGuard/);assert.match(main,/WORKER_SCOPE_MISMATCH/);assert.match(main,/SCOPE_LOCK_REQUIRED/);assert.match(main,/WORKTREE_LEASE_REQUIRED/);});
check("checkpoint auto-send is transcript confirmed",()=>{assert.match(main,/action === "checkpoint"[\s\S]*sendPreparedChatPrompt\(view, marker\)[\s\S]*verifyPromptMarkerInTranscript\(view, marker, 12000\)/);assert.match(main,/checkpointTranscriptVerified:true/);});
check("checkpoint has lifecycle states",()=>{for(const s of ["PREPARING","SENT_CONFIRMED","WAITING_RESPONSE"])assert.match(main,new RegExp('checkpointState:"'+s+'"'));assert.match(main,/checkpointState:passed \? "PASS" : "BLOCKED"/);assert.match(main,/checkpointState:"BLOCKED"/);});
check("checkpoint stage report monitored",()=>assert.match(main,/checkpointPending[\s\S]*checkpointReportHead:report\.head[\s\S]*checkpointReportEvidence:report\.evidence/));
check("checkpoint prompt explicitly forbids full build",()=>assert.match(prompt,/FULL BUILD.*tilos|FULL BUILD-et.*ne indíts/i));
check("checkpoint implementation never calls full build",()=>{
  const start=main.indexOf('if (action === "checkpoint")');
  const end=main.indexOf('const prompt = buildStageActionPrompt',start);
  assert.ok(start>=0&&end>start);
  assert.doesNotMatch(main.slice(start,end),/requestDeveloperGridFullBuild|build-runs:request|next build|build:raw/);
});
check("no new TASK_LAUNCH is generated by Task/Context/Checkpoint UI",()=>{
  const start=renderer.indexOf("async function handleStageAction");
  const end=renderer.indexOf("function renderStageActions",start);
  assert.ok(start>=0&&end>start);
  assert.doesNotMatch(renderer.slice(start,end),/prepareTaskLaunch|startDeveloperGridWork|TASK_LAUNCH/);
});
check("live task exposes authoritative source proof",()=>{assert.match(live,/sourceProofSha256: context\.sourceExecutionProof\?\.sha256/);assert.match(live,/sourceProofActiveScopeLockCount/);assert.match(live,/sourceProofActiveWorktreeLeaseCount/);});
check("PROD remains denied",()=>{assert.match(main,/PROD DENY/);assert.match(prompt,/DEV ONLY · PROD DENY/);assert.match(live,/sourceProofProductionAccess: context\.sourceExecutionProof\?\.productionAccess \|\| "DENY"/);});

console.log("Developer Grid Task / Context / Checkpoint v0.1.52 contract PASS · "+n+"/"+n);
