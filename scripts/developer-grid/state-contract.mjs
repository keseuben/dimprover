const store = await import(`file://${storePath}?v=${Date.now()}`);
const stateRoot = path.join(tmp, "state");
const task = { id:"task-1", projectId:"project_dimprover", title:"Developer Grid", priority:98, environment:"DEV", productionAccess:"DENY", status:"RUNNING", acceptance:[] };
const context = { projectId:"project_dimprover", mainModule:"BENJADMIN", moduleName:"Developer Grid V1", submoduleName:"foundation", workItem:"state", workStageIndex:2, taskId:"task-1", source:"EXPLICIT_TASK", resolvedAt:new Date().toISOString() };
