import assert from "node:assert/strict";
import { classifyDriveAccessGrant } from "../../app/lib/drive-core/driveLicenseCore.ts";
import { readFileSync } from "node:fs";
const now=Date.parse("2026-10-11T12:00:00Z");
const grant={valid_from:"2026-10-01T00:00:00Z",valid_until:null,revoked_at:null};
assert.equal(classifyDriveAccessGrant(grant,now),"ACTIVE");
assert.equal(classifyDriveAccessGrant({...grant,valid_from:"2026-10-12T00:00:00Z"},now),"PENDING");
assert.equal(classifyDriveAccessGrant({...grant,valid_until:"2026-10-10T00:00:00Z"},now),"EXPIRED");
assert.equal(classifyDriveAccessGrant({...grant,revoked_at:"2026-10-11T00:00:00Z"},now),"REVOKED");
assert.equal(classifyDriveAccessGrant({...grant,valid_until:"2026-10-11T12:00:00Z"},now),"ACTIVE","valid until inclusive");
const route=readFileSync("app/api/drive/license/route.ts","utf8");
assert.ok(route.includes("resolveProjectCoreAuth(request)"),"AUTH session is required");
assert.ok(route.includes("WHERE g.user_id = $1::uuid"),"AUTH grants query is user-scoped");
assert.ok(route.includes("[access.actor.userId]"),"only authenticated actor may supply user ID");
assert.ok(route.includes('status: "UNLINKED"'),"paid subscription never inferred from access rights");
assert.ok(route.includes("listAccessibleProjects(access.actor.userAliases)"),"project access is scoped");
assert.ok(!route.includes("x-dimpro-license-admin-key"),"no admin license key on personal API");
const menu=readFileSync("components/drive/FloatingProjectBoard.tsx","utf8");
assert.ok(menu.includes('href="/drive/licenc"'),"Drive expanded menu provides license link");
const mail=readFileSync("app/lib/dimpro-auth/drive-registration-operator.ts","utf8");
assert.ok(mail.includes('APPROVED_DRIVE_OPERATOR_EMAIL = "admin@dimpro.hu"'),"approved operator address is explicit");
assert.ok(mail.includes("DRIVE_OPERATOR_MAIL_RELEASED: boolean = false"),"no operator email until release");
