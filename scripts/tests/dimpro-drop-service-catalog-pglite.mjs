import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {pathToFileURL} from "node:url";
const modulePath=process.env.DIMPRO_TEST_PGLITE_MODULE_PATH;
if(!modulePath)throw Error("PGlite module required");
const {PGlite}=await import(pathToFileURL(modulePath).href);
const db=new PGlite();
try{
 await db.exec("CREATE ROLE dimpro_auth_migrator_dev; CREATE ROLE dimpro_auth_app_dev; GRANT USAGE,CREATE ON SCHEMA public TO dimpro_auth_migrator_dev; GRANT USAGE ON SCHEMA public TO dimpro_auth_app_dev; SET ROLE dimpro_auth_migrator_dev;");
 await db.exec("CREATE TABLE public.auth_products (id uuid PRIMARY KEY DEFAULT gen_random_uuid(),code text NOT NULL UNIQUE,name text NOT NULL,status text NOT NULL CHECK(status IN ('ACTIVE','DISABLED')));");
 await db.exec("INSERT INTO public.auth_products(code,name,status) VALUES ('DRIVE','Existing Drive','ACTIVE'),('PROJECT_GATE','Existing Projektkapu','ACTIVE'),('DIMPRO_DROP','Existing Drop','ACTIVE');");
 await db.exec(readFileSync("db/auth/migrations/018_auth_v055_dimpro_product_topology.sql","utf8"));
 await db.exec(readFileSync("db/auth/migrations/020_auth_v057_dimpro_mini_app_catalog.sql","utf8"));
 await db.exec(readFileSync("db/auth/migrations/021_auth_v058_dimpro_drop_shared_service.sql","utf8"));
 let result=await db.query("SELECT * FROM public.auth_connected_service_catalog");
 assert.equal(result.rows.length,1);
 const row=result.rows[0];
 assert.equal(row.product_code,"DIMPRO_DROP");
 assert.equal(row.companion_product_code,"DRIVE");
 assert.deepEqual(row.license_scopes,["USER","ORGANIZATION"]);
 assert.equal(row.requires_companion_license,false);
 assert.equal(row.integration_policy,"OPTIONAL_PROJECT_ACL_GATED");
 assert.equal(row.storage_policy,"TEMPORARY_TRANSFER_SEPARATE_FROM_DRIVE");
 assert.equal(row.commercial_state,"MIGRATION_PLANNED");
 assert.equal(row.legacy_cutover_released,false);
 assert.equal(row.entitlement_enabled,false);
 result=await db.query("SELECT code,name,status FROM public.auth_products ORDER BY code");
 assert.equal(result.rows.length,12,"5 levels, Drive, 5 mini apps, Drop");
 assert.equal(result.rows.find(x=>x.code==="DIMPRO_DROP").name,"Existing Drop","existing product name unchanged");
 assert.equal(result.rows.find(x=>x.code==="DIMPRO_DROP").status,"ACTIVE","existing SSO status unchanged");
 assert.equal(result.rows.find(x=>x.code==="DRIVE").status,"ACTIVE");
 assert.equal(result.rows.find(x=>x.code==="PROJECT_GATE").status,"ACTIVE");
 assert.equal((await db.query("SELECT count(*)::int AS n FROM public.auth_product_scope_catalog")).rows[0].n,6);
 assert.equal((await db.query("SELECT count(*)::int AS n FROM public.auth_mini_app_catalog")).rows[0].n,5);
 await assert.rejects(()=>db.query("UPDATE public.auth_connected_service_catalog SET entitlement_enabled=true"),/check constraint/i);
 await assert.rejects(()=>db.query("UPDATE public.auth_connected_service_catalog SET legacy_cutover_released=true"),/check constraint/i);
 await assert.rejects(()=>db.query("UPDATE public.auth_connected_service_catalog SET requires_companion_license=true"),/check constraint/i);
 await assert.rejects(()=>db.query("UPDATE public.auth_connected_service_catalog SET commercial_state='ACTIVE'"),/check constraint/i);
 await db.exec("RESET ROLE;SET ROLE dimpro_auth_app_dev;");
 assert.equal((await db.query("SELECT count(*)::int AS n FROM public.auth_connected_service_catalog")).rows[0].n,1);
 await assert.rejects(()=>db.query("UPDATE public.auth_connected_service_catalog SET commercial_state='MIGRATION_PLANNED'"),/permission denied/i);
 await db.exec("RESET ROLE;");
 console.log("DIMPRO DROP SHARED SERVICE PGLITE 12-PRODUCT ISOLATION PASS");
}finally{await db.close();}
