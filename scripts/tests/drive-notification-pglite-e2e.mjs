    assert.equal(row.outcome.status,"RESERVED");
    const id2=row.outcome.deliveryId;
    const token2="e0000000-0000-4000-a000-000000000002";
    row=await first("SELECT public.drive_digest_claim_delivery($1::uuid,$2::uuid) AS ticket",[id2,token2]);
    assert.equal(row.ticket.cursorFrom,250);
    row=await first("SELECT public.drive_digest_finish_without_acceptance($1::uuid,$2::uuid,'SUPPRESSED','CONSENT_REVOKED') AS done",[id2,token2]);
    assert.equal(row.done,true);
    row=await first("SELECT last_success_sequence AS cursor FROM public.drive_core_notification_preferences WHERE project_id='p' AND user_id='u'");
    assert.equal(Number(row.cursor),252);
    row=await first("SELECT count(*)::int AS total FROM public.drive_core_digest_deliveries WHERE project_id='p'");
    assert.equal(row.total,2);
    await db.exec("INSERT INTO public.drive_core_document_metadata(id,project_id,document_id,extra,updated_by) VALUES ('m','p','doc','{}'::jsonb,'actor');");
    row=await first("SELECT count(*)::int AS total FROM public.drive_core_change_events WHERE event_type='DOCUMENT_REVIEW_DECISION_CHANGED'");
    assert.equal(row.total,0);
    await db.exec("UPDATE public.drive_core_document_metadata SET extra=jsonb_build_object('topic','epulet') WHERE id='m';");
    row=await first("SELECT count(*)::int AS total FROM public.drive_core_change_events WHERE event_type='DOCUMENT_REVIEW_DECISION_CHANGED'");
    assert.equal(row.total,0);
    await db.exec("UPDATE public.drive_core_document_metadata SET extra=jsonb_build_object('topic','epulet','reviewChecked',true) WHERE id='m';");
    row=await first("SELECT count(*)::int AS total FROM public.drive_core_change_events WHERE event_type='DOCUMENT_REVIEW_DECISION_CHANGED'");
    assert.equal(row.total,1);
    row=await first("SELECT cursor_to FROM public.drive_core_digest_deliveries WHERE id=$1::uuid",[id1]);
    assert.equal(Number(row.cursor_to),250);
    await assert.rejects(
      () => query("SELECT public.drive_digest_register_journal_page('p','u','DOCUMENT_CHANGES','DAILY','2026-10-10T07:00-Europe/Budapest',252,400,ARRAY[]::text[])"),
      /DRIVE_DIGEST_CURSOR_RANGE_NOT_VERIFIED/,
      "phantom cursor can never advance"
    );
    row=await first("SELECT public.drive_set_digest_preference('p','u','DOCUMENT_CHANGES',false,'DAILY',false) AS ok");
    assert.equal(row.ok,true);
    row=await first("SELECT public.drive_digest_register_journal_page('p','u','DOCUMENT_CHANGES','DAILY','2026-10-10T07:00-Europe/Budapest',252,253,ARRAY[]::text[]) AS outcome");
    assert.equal(row.outcome.status,"CONSENT_REVOKED");
    row=await first("SELECT last_success_sequence AS cursor FROM public.drive_core_notification_preferences WHERE project_id='p' AND user_id='u'");
    assert.equal(Number(row.cursor),252);
    console.log("PG_SANDBOX_TRANSACTION_CONTRACT_PASS");
