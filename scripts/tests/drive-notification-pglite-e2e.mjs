    row=await first("SELECT public.drive_digest_claim_delivery($1::uuid,$2::uuid) AS ticket",[id1,token1]);
    assert.equal(row.ticket.cursorTo,250);
    row=await first("SELECT public.drive_digest_claim_delivery($1::uuid,gen_random_uuid()) AS ticket",[id1]);
    assert.equal(row.ticket,null,"second worker blocked");
    row=await first("SELECT public.drive_digest_ack_smtp_acceptance($1::uuid,$2::uuid,'<msg-1>',$3::text) AS ack",[id1,token1,"a".repeat(64)]);
