    await db.exec("INSERT INTO public.drive_core_change_events(id,project_id,event_type,entity_type,entity_id,payload,actor_user_id) SELECT 'event-'||n,'p','DOCUMENT_VERSION_CREATED','document_version','version-'||n,jsonb_build_object('documentId','doc'),'actor' FROM generate_series(1,252) AS n;");
    row=await first("SELECT public.drive_digest_register_journal_page('p','u','DOCUMENT_CHANGES','DAILY','2026-10-10T07:00-Europe/Budapest',0,250,ARRAY(SELECT 'event-'||n FROM generate_series(1,250) n)) AS outcome");
    console.log("FIRST_BATCH",JSON.stringify(row.outcome));
    assert.equal(row.outcome.status,"RESERVED");
    const id1=row.outcome.deliveryId;
    row=await first("SELECT public.drive_digest_register_journal_page('p','u','DOCUMENT_CHANGES','DAILY','2026-10-10T07:00-Europe/Budapest',0,250,ARRAY['event-1']) AS outcome");
