    row=await first("SELECT last_success_sequence AS cursor FROM public.drive_core_notification_preferences WHERE project_id='p' AND user_id='u'");
    assert.equal(Number(row.cursor),250);
    row=await first("SELECT public.drive_digest_register_journal_page('p','u','DOCUMENT_CHANGES','DAILY','2026-10-10T07:00-Europe/Budapest',250,252,ARRAY['event-251','event-252']) AS outcome");
