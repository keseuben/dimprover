import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {pathToFileURL} from "node:url";
const modulePath=process.env.DIMPRO_TEST_PGLITE_MODULE_PATH;
if(!modulePath)throw Error("Isolated PostgreSQL test module path is required");
const {PGlite}=await import(pathToFileURL(modulePath).href);
const db=new PGlite();
const id="cdf8f63e-61ea-4f34-972d-e94a58c1b298";
const other="adb5cbb2-6715-4626-a2e1-36d101da824d";
const exec=async sql=>await db.exec(sql);
try {
  await exec("CREATE ROLE dimpro_auth_migrator_dev; CREATE ROLE dimpro_auth_app_dev; GRANT USAGE,CREATE ON SCHEMA public TO dimpro_auth_migrator_dev; GRANT USAGE ON SCHEMA public TO dimpro_auth_app_dev;");
  await exec("SET ROLE dimpro_auth_migrator_dev");
  await exec("CREATE TABLE public.auth_drive_registration_requests (id uuid PRIMARY KEY, email_normalized text NOT NULL, display_name text, organization_name text, status text NOT NULL, requested_at timestamptz NOT NULL DEFAULT now(), email_verified_at timestamptz); GRANT SELECT ON public.auth_drive_registration_requests TO dimpro_auth_app_dev;");
  await db.query("INSERT INTO public.auth_drive_registration_requests(id,email_normalized,display_name,organization_name,status) VALUES($1,'alice@example.com','Alice','Example Company','PENDING_EMAIL'),($2,'pending@example.com','Pending','Example','PENDING_EMAIL')",[id,other]);
  await exec(readFileSync("db/auth/migrations/013_auth_v050_drive_registration_operator_notices.sql","utf8"));
  let n=await db.query("SELECT count(*)::int AS n FROM public.auth_drive_registration_operator_notices");
  assert.equal(n.rows[0].n,0,"unverified requests do not enqueue");
  await db.query("UPDATE public.auth_drive_registration_requests SET status='EMAIL_VERIFIED',email_verified_at=now() WHERE id=$1",[id]);
  n=await db.query("SELECT count(*)::int AS n FROM public.auth_drive_registration_operator_notices");
  assert.equal(n.rows[0].n,1,"single verified request queued atomically");
  await db.query("UPDATE public.auth_drive_registration_requests SET status='PENDING_EMAIL' WHERE id=$1",[id]);
  await db.query("UPDATE public.auth_drive_registration_requests SET status='EMAIL_VERIFIED' WHERE id=$1",[id]);
  n=await db.query("SELECT count(*)::int AS n FROM public.auth_drive_registration_operator_notices");
  assert.equal(n.rows[0].n,1,"deduplicates re-verification");
  await exec("RESET ROLE; SET ROLE dimpro_auth_app_dev;");
  let claim=await db.query("SELECT * FROM public.auth_claim_drive_registration_operator_notice($1::uuid)",[other]);
  assert.equal(claim.rows.length,0,"unverified request cannot be claimed");
  claim=await db.query("SELECT * FROM public.auth_claim_drive_registration_operator_notice($1::uuid)",[id]);
  assert.equal(claim.rows.length,1);
  const token=claim.rows[0].notice_claim_token;
  assert.equal(claim.rows[0].applicant_email,"alice@example.com");
  assert.equal(claim.rows[0].applicant_organization,"Example Company");
  let second=await db.query("SELECT * FROM public.auth_claim_drive_registration_operator_notice($1::uuid)",[id]);
  assert.equal(second.rows.length,0,"concurrent or repeated claim cannot resend");
  let finish=await db.query("SELECT public.auth_complete_drive_registration_operator_notice($1::uuid,$2::uuid,'SENT') AS ok",[id,"00000000-0000-4000-8000-000000000000"]);
  assert.equal(finish.rows[0].ok,false,"wrong claim token blocked");
  await assert.rejects(()=>db.query("SELECT public.auth_complete_drive_registration_operator_notice($1::uuid,$2::uuid,'PENDING')",[id,token]),/INVALID/);
  finish=await db.query("SELECT public.auth_complete_drive_registration_operator_notice($1::uuid,$2::uuid,'SENT') AS ok",[id,token]);
  assert.equal(finish.rows[0].ok,true,"SMTP acceptance acknowledged once");
  finish=await db.query("SELECT public.auth_complete_drive_registration_operator_notice($1::uuid,$2::uuid,'SENT') AS ok",[id,token]);
  assert.equal(finish.rows[0].ok,false,"cannot finish twice");
  second=await db.query("SELECT * FROM public.auth_claim_drive_registration_operator_notice($1::uuid)",[id]);
  assert.equal(second.rows.length,0,"completed notice cannot resend");
  await exec("RESET ROLE");
  n=await db.query("SELECT status,attempt_count,claim_token IS NOT NULL AS has_token,sent_at IS NOT NULL AS sent FROM public.auth_drive_registration_operator_notices WHERE registration_id=$1",[id]);
  assert.deepEqual(n.rows[0],{status:"SENT",attempt_count:1,has_token:true,sent:true});
  // Distinct failure-ambiguous branch must not create duplicate notifications.
  await db.query("UPDATE public.auth_drive_registration_requests SET status='EMAIL_VERIFIED',email_verified_at=now() WHERE id=$1",[other]);
  await exec("SET ROLE dimpro_auth_app_dev");
  const secondClaim=await db.query("SELECT * FROM public.auth_claim_drive_registration_operator_notice($1::uuid)",[other]);
  assert.equal(secondClaim.rows.length,1);
  const ambiguous=await db.query("SELECT public.auth_complete_drive_registration_operator_notice($1::uuid,$2::uuid,'AMBIGUOUS') AS ok",
    [other,secondClaim.rows[0].notice_claim_token]);
  assert.equal(ambiguous.rows[0].ok,true);
  const neverResend=await db.query("SELECT * FROM public.auth_claim_drive_registration_operator_notice($1::uuid)",[other]);
  assert.equal(neverResend.rows.length,0);
  await exec("RESET ROLE");
  const ambiguousStatus=await db.query("SELECT status FROM public.auth_drive_registration_operator_notices WHERE registration_id=$1",[other]);
  assert.equal(ambiguousStatus.rows[0].status,"AMBIGUOUS");
  await exec("CREATE ROLE dimpro_auth_guest; GRANT USAGE ON SCHEMA public TO dimpro_auth_guest; SET ROLE dimpro_auth_guest");
  await assert.rejects(()=>db.query("SELECT * FROM public.auth_claim_drive_registration_operator_notice($1::uuid)",[id]),/permission denied/);
  await exec("RESET ROLE");
  console.log("AUTH DRIVE OPERATOR DURABLE OUTBOX PGLITE: 18/18 PASS");
}finally {await db.close();}
