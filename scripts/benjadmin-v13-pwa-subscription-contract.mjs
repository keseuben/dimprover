#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
const root=process.cwd();
const read=(file)=>fs.readFileSync(path.join(root,file),"utf8");
const pushStore=read("app/lib/dev-center/push-store.ts");
const publicKey=read("app/api/dev/push/public-key/route.ts");
const testRoute=read("app/api/dev/push/test/route.ts");
const controls=read("components/admin/DevPwaControls.tsx");
const css=read("app/admin/admin-theme.css");
const sw=read("public/dimpro-dev-sw.js");
let passed=0;
function check(name,fn){fn();passed++;console.log(`PASS ${name}`)}
check("Push store uses DIMPRO_PROJECT_ROOT",()=>assert.ok(pushStore.includes("process.env.DIMPRO_PROJECT_ROOT?.trim()")));
check("Push store resolves configured root",()=>assert.ok(pushStore.includes("return path.resolve(configuredRoot)")));
check("Push store stays under shared dev-center data",()=>assert.ok(pushStore.includes('path.join(getRuntimeProjectRoot(), ".data", "dimpro-dev-center")')));
check("Push store filename stable",()=>assert.ok(pushStore.includes('"push-subscriptions.json"')));
check("Push public config exposes configured state",()=>assert.ok(publicKey.includes("configured: Boolean(publicKey)")));
check("Push public config exposes subscription count",()=>assert.ok(publicKey.includes("subscriptionCount: subscriptions.length")));
check("Test push accepts taskId",()=>assert.ok(testRoute.includes("taskId?: string")));
check("Test push validates taskId",()=>assert.ok(testRoute.includes("/^[A-Za-z0-9_-]{4,120}$/")));
check("Test push creates task deep-link",()=>assert.ok(testRoute.includes("/admin/dev-console?task=${encodeURIComponent(taskId)}")));
check("Test push returns target task",()=>assert.ok(testRoute.includes("targetTaskId: taskId || null")));
check("Test push returns target URL",()=>assert.ok(testRoute.includes("targetUrl")));
check("PWA panel refreshes push state",()=>assert.ok(controls.includes("async function refreshPushState")));
check("PWA panel checks browser support",()=>assert.ok(controls.includes('"PushManager" in window')&&controls.includes('"Notification" in window')));
check("PWA panel checks local subscription",()=>assert.ok(controls.includes("registration.pushManager.getSubscription()")));
check("PWA panel checks server readiness",()=>assert.ok(controls.includes("setServerReady(ready)")));
check("PWA panel tracks last check",()=>assert.ok(controls.includes("setLastCheckedAt(new Date().toISOString())")));
check("PWA panel handles denied permission",()=>assert.ok(controls.includes('permission === "denied"')&&controls.includes("Push blokkolva")));
check("PWA panel has state refresh action",()=>assert.ok(controls.includes("Állapot frissítése")));
check("PWA panel has device state hook",()=>assert.ok(controls.includes('data-testid="benjadmin-push-device-state"')));
check("PWA panel reports local device state",()=>assert.ok(controls.includes('Ezen az eszközön: <strong>{subscribed ? "aktív" : "inaktív"}</strong>')));
check("PWA panel reports server device count",()=>assert.ok(controls.includes('Szerveren: <strong>{subscriptionCount} eszköz</strong>')));
check("PWA panel test resolves a real task",()=>assert.ok(controls.includes('fetch("/api/dev/console/live"')&&controls.includes("JSON.stringify({ taskId })")));
check("PWA panel labels task push test",()=>assert.ok(controls.includes("Task push teszt")));
check("PWA device state styling exists",()=>assert.ok(css.includes(".dev-pwa-device-note")));
check("Service worker click still navigates notification URL",()=>assert.ok(sw.includes("event.notification.data?.url")&&sw.includes("existing.navigate(targetUrl)")));
check("No native AI provider introduced",()=>assert.ok(!/OPENAI_API_KEY|ANTHROPIC_API_KEY/.test([pushStore,publicKey,testRoute,controls].join("\n"))));
console.log(JSON.stringify({ok:true,passed,failed:0},null,2));
