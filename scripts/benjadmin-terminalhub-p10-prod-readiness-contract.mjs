import fs from "node:fs";
import path from "node:path";

const root=process.cwd();
const read=(file)=>fs.readFileSync(path.join(root,file),"utf8");
const config=read("app/lib/dev-center/terminal-hub/config.ts");
const types=read("app/lib/dev-center/terminal-hub/types.ts");
const readiness=read("app/lib/dev-center/terminal-hub/prod-readiness.ts");
const coreReadiness=read("app/lib/dev-center/terminal-hub/readiness.ts");
const route=read("app/api/dev/terminal-hub/prod-readiness/route.ts");
const ui=read("components/admin/developer-console/ProdReadinessPanel.tsx");
const hub=read("components/admin/developer-console/TerminalHubWorkspace.tsx");
const css=read("components/admin/developer-console/DeveloperConsole.module.css");
let pass=0,fail=0;
function check(name,ok){if(ok){pass++;console.log(`PASS ${name}`)}else{fail++;console.error(`FAIL ${name}`)}}

check("P10 readiness külön flag",config.includes('BENJADMIN_PROD_READINESS_ENABLED')&&types.includes('prodReadinessEnabled: boolean'));
check("P10 connector külön flag",config.includes('BENJADMIN_PROD_READONLY_CONNECTOR_ENABLED')&&types.includes('prodReadOnlyConnectorEnabled: boolean'));
check("Connector readiness mögött gated",config.includes('flag("BENJADMIN_PROD_READINESS_ENABLED", false) && flag("BENJADMIN_PROD_READONLY_CONNECTOR_ENABLED", false)'));
check("P10 flagek default false",config.includes('flag("BENJADMIN_PROD_READINESS_ENABLED", false)')&&config.includes('flag("BENJADMIN_PROD_READONLY_CONNECTOR_ENABLED", false)'));
check("P10 phase explicit",readiness.includes('P10_PROD_READINESS'));
check("PROD start mode read model",readiness.includes('startMode: "PROD_START"'));
check("PROD default READ_ONLY",readiness.includes('productionDefault: "READ_ONLY"'));
check("PROD AI BLOCKED",readiness.includes('aiVisibility: "BLOCKED"'));
check("Browser direct SSH false",readiness.includes('browserDirectSsh: false'));
check("RAW PROD AI tiltva",readiness.includes('rawProdToAiAllowed: false'));
check("Mutating default deny",readiness.includes('mutatingCommandsDefaultAllowed: false'));
check("Explicit approval kötelező",readiness.includes('explicitApprovalRequired: true'));
check("Release gate kötelező",readiness.includes('releaseGateRequired: true'));
check("Rollback pont kötelező",readiness.includes('rollbackPointRequired: true'));
check("Külön connector kötelező",readiness.includes('separateConnectorRequired: true'));
check("Read-only smoke nem kér terminal executiont",readiness.includes('terminalExecutionRequiredForReadOnlySmoke: false'));
check("PROD terminal ON hard blocker",readiness.includes('flags.prodTerminalEnabled')&&readiness.includes('P10 readiness alatt tiltott'));
check("Terminal execution ON hard blocker",readiness.includes('flags.terminalExecutionEnabled')&&readiness.includes('PROD read-only smoke előtt tiltott'));
check("Windows execution ON hard blocker",readiness.includes('flags.windowsBridgeExecutionEnabled')&&readiness.includes('PROD readiness-szel nem kombinálható'));
check("Read-only smoke csak readiness+connector és no execution",readiness.includes('flags.prodReadinessEnabled && flags.prodReadOnlyConnectorEnabled && !hardBlocked'));
check("P10 állapotok explicit",["DISABLED","CONNECTOR_MISSING","READ_ONLY_READY","BLOCKED"].every((x)=>readiness.includes(x)));
check("P10 API admin-only GET",route.includes('isDevCenterAuthorized(request.headers, false)')&&route.includes('export async function GET'));
check("P10 API nincs mutation",!/export async function (POST|PUT|PATCH|DELETE)/.test(route));
check("P10 API no-store",route.includes('cache-control')&&route.includes('no-store'));
check("P10 API nem indít processzt",!/spawn\(|exec\(|execFile\(|node-pty|ssh\s/i.test(route+readiness));
check("P10 UI readiness API-t olvas",ui.includes('/api/dev/terminal-hub/prod-readiness'));
check("P10 UI READ ONLY látható",ui.includes('READ ONLY connector')&&ui.includes('PROD alapállapot'));
check("P10 UI AI BLOCKED látható",ui.includes('AI BLOCKED')&&ui.includes('RAW PROD adat nem kerülhet AI kontextusba'));
check("P10 UI approval kötelező",ui.includes('Approval: KÖTELEZŐ'));
check("P10 UI rollback kötelező",ui.includes('Rollback: KÖTELEZŐ'));
check("P10 UI execution tiltás látható",ui.includes('PROD terminal:')&&ui.includes('Terminal execution:')&&ui.includes('Windows execution:'));
check("P10 UI nincs connect/ssh/run/deploy action",!/>\s*(?:Connect|SSH|Run|Deploy|Restart|Migration|Futtatás)\s*</i.test(ui));
check("P10 panel Terminal Hubban",hub.includes('import ProdReadinessPanel')&&hub.includes('<ProdReadinessPanel />'));
check("Terminal Hub footer P10 policy",hub.includes('P10 foundation:')&&hub.includes('AI BLOCKED'));
check("P2 PROD blocker fázis-kompatibilis",coreReadiness.includes('A PROD terminal execution flag nem kapcsolható a DEV Terminal Core-hoz.')&&!coreReadiness.includes('P2-ben nem lehet ON'));
check("P10 CSS blokk létezik",css.includes('BENJADMIN Terminal Hub P10')&&css.includes('.prodReadinessPanel'));
const p10css=css.slice(css.indexOf('BENJADMIN Terminal Hub P10'));
check("P10 tipográfia minimum 12px",!/font-size:\s*(?:[0-9]|1[01])px/.test(p10css));
check("PROD readiness nem kapcsolja be prod terminalt",!readiness.includes('BENJADMIN_PROD_TERMINAL_ENABLED=1')&&!ui.includes('PROD terminal: ON'));
check("P10 foundation nem tartalmaz PROD host/credential értéket",!/prod\.dimpro\.hu|213\.160\.|password|privateKey|sshKey/i.test(readiness+route+ui));
check("P10 foundation nem ír adatbázisba",!/(\.insert\(|\.update\(|\.delete\(|\.upsert\(|rpc\()/i.test(readiness+route));

console.log(`SUMMARY ${pass}/${pass+fail} PASS`);
if(fail)process.exit(1);
