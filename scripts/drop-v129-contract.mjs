pass('runtime-version-v129',runtime.includes('version: "DROP 1.2.9"'));
pass('speech-common-accumulator-exists',speech.includes('class DropSpeechTranscriptAccumulator'));
pass('speech-result-index-slots',speech.includes('event.resultIndex')&&speech.includes('this.slots.set(index'));
pass('speech-overlap-dedupe',speech.includes('maxOverlap')&&speech.includes('words.slice(overlap)'));
pass('message-uses-common-speech-engine',transfer.includes('new DropSpeechTranscriptAccumulator()')&&transfer.includes('transcriptAccumulatorRef.current.update(event)'));
pass('image-note-uses-common-speech-engine',uploader.includes('new DropSpeechTranscriptAccumulator()')&&uploader.includes('voiceTranscriptAccumulatorRef.current.update(event)'));
pass('legacy-message-append-removed',!transfer.includes('finalAddition')&&!transfer.includes('interimTextRef'));
pass('legacy-image-append-removed',!uploader.includes('finalAddition')&&!uploader.includes('voiceInterimTextRef'));
pass('microphone-policy-preserved',proxy.includes('microphone=(self)'));
pass('email-mailfile-has-group',email.includes('groupId?: string | null')&&email.includes('groupSortOrder?: number | null'));
pass('finalize-loads-groups',finalize.includes('listDropPackageGroups(input.packageId)')&&finalize.includes('groupSortOrder'));
pass('email-group-summary',email.includes('Csoportok összesítője')&&email.includes('groupAnchor(index)'));
pass('email-table-compatible-groups',email.includes('role="presentation"')&&!email.includes('<details'));
pass('download-service-returns-group',download.includes('groupName: file.group_id')&&download.includes('groupSortOrder'));
pass('download-groups-default-open',panel.includes('useState<Set<string>>(() => new Set())'));
pass('download-groups-collapsible',panel.includes('toggleGroup(group.key)')&&panel.includes('aria-expanded={!collapsed}'));
pass('download-summary-reopens',panel.includes('next.delete(key)')&&panel.includes('scrollIntoView'));
pass('download-group-summary',panel.includes('Csoportok összesítője'));
pass('pdf-four-grid-2x2',renderer.includes('.image-layout-4 { grid-template-columns:repeat(2,minmax(0,1fr)); grid-template-rows:repeat(2,minmax(0,1fr)); }'));
pass('pdf-six-grid-3x2',renderer.includes('.image-layout-6 { grid-template-columns:repeat(3,minmax(0,1fr)); grid-template-rows:repeat(2,minmax(0,1fr)); }'));
pass('pdf-group-header',renderer.includes('image-group-header')&&renderer.includes('break-after: avoid'));
pass('pdf-dense-comment-limit',renderer.includes('compactReportComment')&&renderer.includes('imagesPerPage === 4 ? 260 : 130'));
pass('txt-group-summary',textReport.includes('CSOPORTÖSSZESÍTŐ'));
pass('txt-group-sections',textReport.includes('=== ${clean(group.name).toLocaleUpperCase("hu-HU")}'));
pass('ungrouped-last-email',email.includes('left.ungrouped ? 1 : -1'));
pass('ungrouped-last-download',panel.includes('left.ungrouped ? 1 : -1'));
pass('ungrouped-last-pdf',renderer.includes('left.ungrouped ? 1 : -1'));
pass('ungrouped-last-txt',textReport.includes('left.ungrouped ? 1 : -1'));
console.log(JSON.stringify({ok:true,version:'DROP 1.2.9',checks:checks.length,names:checks},null,2));
