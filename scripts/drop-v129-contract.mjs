import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const checks=[];
const pass=(name,condition,detail='')=>{assert.ok(condition,`${name}${detail?`: ${detail}`:''}`);checks.push(name)};
const transfer=await readFile('components/drop/DropPublicTransferClient.tsx','utf8');
const uploader=await readFile('components/drop/DropPublicHexUploader.tsx','utf8');
const speech=await readFile('components/drop/dropSpeechTranscript.ts','utf8');
const email=await readFile('app/lib/drop/public/dropPublicEmailTemplate.ts','utf8');
const finalize=await readFile('app/lib/drop/public/dropPublicFinalizeService.ts','utf8');
const download=await readFile('app/lib/drop/download/dropDownloadService.ts','utf8');
