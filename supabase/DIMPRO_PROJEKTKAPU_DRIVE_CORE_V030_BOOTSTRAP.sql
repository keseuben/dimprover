create or replace function public.drive_core_create_folder_atomic(
  p_project_id text,
  p_folder jsonb,
  p_actor_user_id text
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_folder public.drive_core_folders;
  v_parent public.drive_core_folders;
  v_path text;
begin
  if not exists (select 1 from public.project_core_projects where id = p_project_id and status <> 'DELETED') then
    raise exception 'DRIVE_CORE_PROJECT_NOT_FOUND' using errcode = 'P0002';
  end if;

  if nullif(p_folder->>'parent_id','') is not null then
    select * into v_parent from public.drive_core_folders
      where id = p_folder->>'parent_id' and project_id = p_project_id and status = 'ACTIVE';
    if v_parent.id is null then
      raise exception 'DRIVE_CORE_PARENT_NOT_FOUND' using errcode = 'P0002';
    end if;
    v_path := v_parent.path || '/' || btrim(p_folder->>'name');
  else
    v_path := btrim(p_folder->>'name');
  end if;

  insert into public.drive_core_folders (
    id, project_id, parent_id, name, path, sort_order, status, created_by, created_at, updated_at
  ) values (
    p_folder->>'id', p_project_id, nullif(p_folder->>'parent_id',''), btrim(p_folder->>'name'), v_path,
    coalesce((p_folder->>'sort_order')::integer,100), 'ACTIVE', p_actor_user_id, now(), now()
  ) returning * into v_folder;

  insert into public.project_core_audit_events (
    id, project_id, actor_user_id, event_type, entity_type, entity_id, summary, metadata
  ) values (
    'project-audit-' || substr(replace(gen_random_uuid()::text,'-',''),1,12), p_project_id, p_actor_user_id,
    'DRIVE_FOLDER_CREATED','folder',v_folder.id,'DRIVE mappa létrehozva: ' || v_folder.path,
    jsonb_build_object('path',v_folder.path,'parentId',v_folder.parent_id)
  );

  insert into public.drive_core_change_events (id, project_id, event_type, entity_type, entity_id, payload, actor_user_id)
  values ('drive-change-' || substr(replace(gen_random_uuid()::text,'-',''),1,16), p_project_id,
    'FOLDER_CREATED','folder',v_folder.id,to_jsonb(v_folder),p_actor_user_id);

  return to_jsonb(v_folder);
end;
$$;

create or replace function public.drive_core_create_document_atomic(
  p_project_id text,
  p_document jsonb,
  p_version jsonb,
  p_actor_user_id text
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_document public.drive_core_documents;
  v_version public.drive_core_document_versions;
begin
  if not exists (
    select 1 from public.drive_core_folders
    where id = p_document->>'folder_id' and project_id = p_project_id and status = 'ACTIVE'
  ) then
    raise exception 'DRIVE_CORE_FOLDER_NOT_FOUND' using errcode = 'P0002';
  end if;

  insert into public.drive_core_documents (
    id, project_id, folder_id, name, extension, mime_type, description, status, source,
    current_version_number, created_by, created_at, updated_at
  ) values (
    p_document->>'id', p_project_id, p_document->>'folder_id', p_document->>'name',
    coalesce(p_document->>'extension',''), coalesce(p_document->>'mime_type','application/octet-stream'),
    coalesce(p_document->>'description',''), 'ACTIVE', coalesce(p_document->>'source','WEB'),
    1, p_actor_user_id, coalesce(nullif(p_document->>'created_at','')::timestamptz,now()),
    coalesce(nullif(p_document->>'updated_at','')::timestamptz,now())
  ) returning * into v_document;

  insert into public.drive_core_document_versions (
    id, project_id, document_id, version_number, revision_code, original_name, mime_type, size_bytes,
    sha256, storage_provider, storage_bucket, storage_key, status, change_note, created_by, created_at
  ) values (
    p_version->>'id', p_project_id, v_document.id, 1, coalesce(p_version->>'revision_code','V1'),
    p_version->>'original_name', coalesce(p_version->>'mime_type',v_document.mime_type),
    coalesce((p_version->>'size_bytes')::bigint,0), nullif(p_version->>'sha256',''),
    'METADATA_ONLY', null, null, 'METADATA_ONLY', coalesce(p_version->>'change_note',''),
    p_actor_user_id, coalesce(nullif(p_version->>'created_at','')::timestamptz,now())
  ) returning * into v_version;

  insert into public.project_core_audit_events (
    id, project_id, actor_user_id, event_type, entity_type, entity_id, summary, metadata
  ) values (
    'project-audit-' || substr(replace(gen_random_uuid()::text,'-',''),1,12), p_project_id, p_actor_user_id,
    'DRIVE_DOCUMENT_CREATED','document',v_document.id,'DRIVE dokumentum létrehozva: ' || v_document.name,
    jsonb_build_object('folderId',v_document.folder_id,'version',1,'storageMode','METADATA_ONLY')
  );

  insert into public.drive_core_change_events (id, project_id, event_type, entity_type, entity_id, payload, actor_user_id)
  values ('drive-change-' || substr(replace(gen_random_uuid()::text,'-',''),1,16), p_project_id,
    'DOCUMENT_CREATED','document',v_document.id,
    jsonb_build_object('document',to_jsonb(v_document),'version',to_jsonb(v_version)),p_actor_user_id);

  return jsonb_build_object('document',to_jsonb(v_document),'version',to_jsonb(v_version));
end;
$$;

create or replace function public.drive_core_add_version_atomic(
  p_project_id text,
  p_document_id text,
  p_version jsonb,
  p_actor_user_id text
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_document public.drive_core_documents;
  v_version public.drive_core_document_versions;
  v_expected integer;
  v_next integer;
begin
  select * into v_document from public.drive_core_documents
    where id = p_document_id and project_id = p_project_id and status = 'ACTIVE' for update;
  if v_document.id is null then
    raise exception 'DRIVE_CORE_DOCUMENT_NOT_FOUND' using errcode = 'P0002';
  end if;

  v_expected := coalesce((p_version->>'expected_current_version')::integer,0);
  if v_expected > 0 and v_expected <> v_document.current_version_number then
    raise exception 'DRIVE_CORE_VERSION_CONFLICT' using errcode = 'P0001';
  end if;
  v_next := v_document.current_version_number + 1;

  insert into public.drive_core_document_versions (
    id, project_id, document_id, version_number, revision_code, original_name, mime_type, size_bytes,
    sha256, storage_provider, storage_bucket, storage_key, status, change_note, created_by, created_at
  ) values (
    p_version->>'id', p_project_id, p_document_id, v_next,
    coalesce(nullif(p_version->>'revision_code',''),'V' || v_next::text), p_version->>'original_name',
    coalesce(p_version->>'mime_type',v_document.mime_type), coalesce((p_version->>'size_bytes')::bigint,0),
    nullif(p_version->>'sha256',''), 'METADATA_ONLY', null, null, 'METADATA_ONLY',
    coalesce(p_version->>'change_note',''), p_actor_user_id,
    coalesce(nullif(p_version->>'created_at','')::timestamptz,now())
  ) returning * into v_version;

  update public.drive_core_documents
  set current_version_number = v_next,
      mime_type = v_version.mime_type,
      updated_at = now()
  where id = p_document_id
  returning * into v_document;

  insert into public.project_core_audit_events (
    id, project_id, actor_user_id, event_type, entity_type, entity_id, summary, metadata
  ) values (
    'project-audit-' || substr(replace(gen_random_uuid()::text,'-',''),1,12), p_project_id, p_actor_user_id,
    'DRIVE_DOCUMENT_VERSION_CREATED','document_version',v_version.id,
    'Új DRIVE dokumentumverzió: ' || v_document.name || ' · V' || v_next::text,
    jsonb_build_object('documentId',v_document.id,'version',v_next,'storageMode','METADATA_ONLY')
  );

  insert into public.drive_core_change_events (id, project_id, event_type, entity_type, entity_id, payload, actor_user_id)
  values ('drive-change-' || substr(replace(gen_random_uuid()::text,'-',''),1,16), p_project_id,
    'DOCUMENT_VERSION_CREATED','document_version',v_version.id,
    jsonb_build_object('document',to_jsonb(v_document),'version',to_jsonb(v_version)),p_actor_user_id);

  return jsonb_build_object('document',to_jsonb(v_document),'version',to_jsonb(v_version));
end;
$$;

create or replace function public.drive_core_upsert_sync_cursor(
  p_project_id text,
  p_client_id text,
  p_machine_name text,
  p_cursor_value bigint,
  p_metadata jsonb,
  p_actor_user_id text
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_cursor public.drive_core_sync_cursors;
  v_id text;
begin
  if not exists (select 1 from public.project_core_projects where id = p_project_id and status <> 'DELETED') then
    raise exception 'DRIVE_CORE_PROJECT_NOT_FOUND' using errcode = 'P0002';
  end if;
  v_id := 'drive-sync-' || substr(md5(p_project_id || ':' || p_client_id),1,20);
  insert into public.drive_core_sync_cursors (
    id, project_id, client_id, machine_name, cursor_value, last_sync_at, metadata, created_at, updated_at
  ) values (
    v_id, p_project_id, p_client_id, nullif(p_machine_name,''), greatest(p_cursor_value,0), now(),
    coalesce(p_metadata,'{}'::jsonb), now(), now()
  )
  on conflict (project_id, client_id) do update set
    machine_name = coalesce(excluded.machine_name,public.drive_core_sync_cursors.machine_name),
    cursor_value = greatest(public.drive_core_sync_cursors.cursor_value,excluded.cursor_value),
    last_sync_at = now(), metadata = excluded.metadata, updated_at = now()
  returning * into v_cursor;

  insert into public.drive_core_change_events (id, project_id, event_type, entity_type, entity_id, payload, actor_user_id)
  values ('drive-change-' || substr(replace(gen_random_uuid()::text,'-',''),1,16), p_project_id,
    'SYNC_CURSOR_UPDATED','sync',v_cursor.id,
    jsonb_build_object('clientId',v_cursor.client_id,'cursorValue',v_cursor.cursor_value,'machineName',v_cursor.machine_name),p_actor_user_id);
  return to_jsonb(v_cursor);
end;
$$;

create or replace function public.drive_core_bootstrap_project(
  p_project_id text,
  p_actor_user_id text
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_existing public.drive_core_project_bootstraps;
  v_item record;
  v_parent_id text;
  v_folder_id text;
  v_inserted integer := 0;
  v_row_count integer;
begin
  if not exists (select 1 from public.project_core_projects where id = p_project_id and status <> 'DELETED') then
    raise exception 'DRIVE_CORE_PROJECT_NOT_FOUND' using errcode = 'P0002';
  end if;
  select * into v_existing from public.drive_core_project_bootstraps where project_id = p_project_id for update;
  if v_existing.project_id is not null then
    return jsonb_build_object('projectId',p_project_id,'folders',v_existing.folder_count,'alreadyBootstrapped',true);
  end if;

  for v_item in select * from (values
    ('01_Tervek',10),('02_Muszaki_dokumentumok',20),('03_Penzugy',30),('04_Szerzodesek',40),
    ('05_Jegyzokonyvek',50),('06_Atadas',60),('99_Archivum',990)
  ) as seed(name,sort_order) loop
    v_folder_id := 'drive-folder-' || substr(md5(p_project_id || ':' || v_item.name),1,20);
    insert into public.drive_core_folders (id,project_id,parent_id,name,path,sort_order,status,created_by)
    values (v_folder_id,p_project_id,null,v_item.name,v_item.name,v_item.sort_order,'ACTIVE',p_actor_user_id)
    on conflict (project_id,path) do nothing;
    get diagnostics v_row_count = row_count;
    v_inserted := v_inserted + v_row_count;
  end loop;

  select id into v_parent_id from public.drive_core_folders where project_id = p_project_id and path = '01_Tervek';
  for v_item in select * from (values ('Epiteszet',10),('Gepeszet',20),('Elektromos',30)) as seed(name,sort_order) loop
    v_folder_id := 'drive-folder-' || substr(md5(p_project_id || ':01_Tervek/' || v_item.name),1,20);
    insert into public.drive_core_folders (id,project_id,parent_id,name,path,sort_order,status,created_by)
    values (v_folder_id,p_project_id,v_parent_id,v_item.name,'01_Tervek/' || v_item.name,v_item.sort_order,'ACTIVE',p_actor_user_id)
    on conflict (project_id,path) do nothing;
    get diagnostics v_row_count = row_count;
    v_inserted := v_inserted + v_row_count;
  end loop;

  insert into public.drive_core_project_bootstraps (project_id,bootstrap_id,folder_count,bootstrapped_by)
  values (p_project_id,'drive-core-v030-20260802',(select count(*) from public.drive_core_folders where project_id=p_project_id),p_actor_user_id);

  insert into public.project_core_audit_events (
    id, project_id, actor_user_id, event_type, entity_type, entity_id, summary, metadata
  ) values (
    'project-audit-' || substr(replace(gen_random_uuid()::text,'-',''),1,12),p_project_id,p_actor_user_id,
    'DRIVE_CORE_BOOTSTRAPPED','project',p_project_id,'A DRIVE Core alapmappái létrejöttek.',
    jsonb_build_object('schemaVersion','0.3.0','insertedFolders',v_inserted)
  );

  insert into public.drive_core_change_events (id,project_id,event_type,entity_type,entity_id,payload,actor_user_id)
  values ('drive-change-' || substr(replace(gen_random_uuid()::text,'-',''),1,16),p_project_id,
    'DRIVE_PROJECT_BOOTSTRAPPED','folder',p_project_id,
    jsonb_build_object('insertedFolders',v_inserted,'schemaVersion','0.3.0'),p_actor_user_id);

  return jsonb_build_object(
    'projectId',p_project_id,
    'folders',(select count(*) from public.drive_core_folders where project_id=p_project_id),
    'insertedFolders',v_inserted,
    'alreadyBootstrapped',false
  );
end;
$$;

