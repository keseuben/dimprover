begin;

create table if not exists public.drive_core_schema_meta (
  component text primary key,
  schema_version text not null,
  migration_count integer not null default 0,
  bootstrap_id text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.drive_core_folders (
  id text primary key,
  project_id text not null references public.project_core_projects(id) on delete cascade,
  parent_id text null references public.drive_core_folders(id) on delete restrict,
  name text not null,
  path text not null,
  sort_order integer not null default 100,
  status text not null default 'ACTIVE',
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint drive_core_folders_name_check check (length(btrim(name)) between 1 and 120 and name !~ '[\\/]'),
  constraint drive_core_folders_path_check check (length(btrim(path)) between 1 and 1200),
  constraint drive_core_folders_status_check check (status in ('ACTIVE','ARCHIVED')),
  constraint drive_core_folders_sort_check check (sort_order between 0 and 999999),
  constraint drive_core_folders_parent_self_check check (parent_id is null or parent_id <> id),
  constraint drive_core_folders_project_path_unique unique (project_id, path)
);

create table if not exists public.drive_core_documents (
  id text primary key,
  project_id text not null references public.project_core_projects(id) on delete cascade,
  folder_id text not null references public.drive_core_folders(id) on delete restrict,
  name text not null,
  extension text not null default '',
  mime_type text not null default 'application/octet-stream',
  description text not null default '',
  status text not null default 'ACTIVE',
  source text not null default 'WEB',
  current_version_number integer not null default 0,
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint drive_core_documents_name_check check (length(btrim(name)) between 1 and 240 and name !~ '[\\/]'),
  constraint drive_core_documents_status_check check (status in ('ACTIVE','ARCHIVED','DELETED')),
  constraint drive_core_documents_source_check check (source in ('WEB','DESKTOP','DROP','SYSTEM')),
  constraint drive_core_documents_version_check check (current_version_number >= 0)
);

create table if not exists public.drive_core_document_versions (
  id text primary key,
  project_id text not null references public.project_core_projects(id) on delete cascade,
  document_id text not null references public.drive_core_documents(id) on delete cascade,
  version_number integer not null,
  revision_code text not null default '',
  original_name text not null,
  mime_type text not null default 'application/octet-stream',
  size_bytes bigint not null default 0,
  sha256 text null,
  storage_provider text not null default 'METADATA_ONLY',
  storage_bucket text null,
  storage_key text null,
  status text not null default 'METADATA_ONLY',
  change_note text not null default '',
  created_by text not null,
  created_at timestamptz not null default now(),
  constraint drive_core_versions_number_check check (version_number > 0),
  constraint drive_core_versions_size_check check (size_bytes >= 0),
  constraint drive_core_versions_sha_check check (sha256 is null or sha256 ~ '^[a-f0-9]{64}$'),
  constraint drive_core_versions_provider_check check (storage_provider in ('METADATA_ONLY','LOCAL_PREVIEW','S3')),
  constraint drive_core_versions_status_check check (status in ('METADATA_ONLY','STAGED','AVAILABLE','QUARANTINED','REJECTED')),
  constraint drive_core_versions_document_number_unique unique (document_id, version_number)
);

create table if not exists public.drive_core_change_events (
  sequence bigint generated by default as identity primary key,
  id text not null unique,
  project_id text not null references public.project_core_projects(id) on delete cascade,
  event_type text not null,
  entity_type text not null,
  entity_id text not null,
  payload jsonb not null default '{}'::jsonb,
  actor_user_id text not null,
  created_at timestamptz not null default now(),
  constraint drive_core_changes_entity_type_check check (entity_type in ('folder','document','document_version','sync'))
