create table if not exists public.drive_core_sync_cursors (
  id text primary key,
  project_id text not null references public.project_core_projects(id) on delete cascade,
  client_id text not null,
  machine_name text null,
  cursor_value bigint not null default 0,
  last_sync_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint drive_core_sync_cursor_value_check check (cursor_value >= 0),
  constraint drive_core_sync_project_client_unique unique (project_id, client_id)
